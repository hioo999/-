DEFAULT_CHARACTERS_BLOCK = "使用默认铁三角：农总 + 淇淇 + 海鸥（人物档案见 SYSTEM 提示词）"


def build_characters_block(custom_characters: list[dict] | None) -> str:
    """把用户自定义的人物列表组装成可注入 prompt 的文本块。

    custom_characters 每项可包含: name, gender, role, personality, catchphrase
    """
    if not custom_characters:
        return DEFAULT_CHARACTERS_BLOCK

    lines: list[str] = ["使用以下自定义人物（请用这些人物代替默认铁三角）："]
    for idx, ch in enumerate(custom_characters, start=1):
        name = (ch.get("name") or "").strip()
        if not name:
            continue
        bits = [f"{idx}. **{name}**"]
        if ch.get("gender"):
            bits.append(f"性别：{ch['gender']}")
        if ch.get("role"):
            bits.append(f"岗位：{ch['role']}")
        if ch.get("personality"):
            bits.append(f"性格底色：{ch['personality']}")
        if ch.get("catchphrase"):
            bits.append(f"口头禅：{ch['catchphrase']}")
        lines.append(" · ".join(bits))

    if len(lines) == 1:
        return DEFAULT_CHARACTERS_BLOCK
    return "\n".join(lines)
